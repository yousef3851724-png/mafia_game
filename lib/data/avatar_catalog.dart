String toPersianPrice(int v) {
  final s = v.toString();
  final b = StringBuffer();
  for (var i = 0; i < s.length; i++) {
    if (i > 0 && (s.length - i) % 3 == 0) b.write('٬');
    b.write(String.fromCharCode(0x06F0 + int.parse(s[i])));
  }
  return b.toString();
}
